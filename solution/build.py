#!/usr/bin/env python3
"""Build solution.html from solution.template.html.

Every 3x3 board in the document is generated by simulating the moves, and the
final state is asserted to be the solved board, so figures and text agree.
Run:  python3 build.py && ./render.sh
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

# ---------------------------------------------------------------- game model
# Cells 0..8 row-major.  A move is a permutation p of cells: the tile in cell i
# travels to cell p[i].
def row_right(r):
    p = list(range(9)); a, b, c = 3 * r, 3 * r + 1, 3 * r + 2
    p[a], p[b], p[c] = b, c, a
    return tuple(p)

def col_down(c):
    p = list(range(9)); a, b, d = c, c + 3, c + 6
    p[a], p[b], p[d] = b, d, a
    return tuple(p)

def inv(p):
    q = [0] * 9
    for i, j in enumerate(p):
        q[j] = i
    return tuple(q)

MOVES = {}
for i in range(3):
    MOVES[f"R{i+1}"] = row_right(i);  MOVES[f"R{i+1}^-1"] = inv(row_right(i))
    MOVES[f"C{i+1}"] = col_down(i);   MOVES[f"C{i+1}^-1"] = inv(col_down(i))

def apply(board, p):
    nb = [0] * 9
    for i, t in enumerate(board):
        nb[p[i]] = t
    return tuple(nb)

SOLVED = tuple(range(1, 10))
START = (1, 2, 3, 4, 8, 5, 7, 6, 9)          # puzzle 2 of the proposal
SEQUENCE = ["R2^-1", "C2^-1", "R2", "C2"]    # executed in this order

# --------------------------------------------------------------- html pieces
def board_html(cells, hl_row=None, hl_col=None, bad=(), good=(), small=False, labels=False):
    """cells: 9 tiles row-major. hl_row/hl_col: 1-based line to tint.
    bad/good: sets of 0-based cell indexes to mark."""
    cls = "board small" if small else "board"
    out = [f'<table class="{cls}" dir="ltr">']
    if labels:
        out.append('<tr class="lab"><td></td><td>C<sub>1</sub></td><td>C<sub>2</sub></td><td>C<sub>3</sub></td></tr>')
    for r in range(3):
        out.append("<tr>")
        if labels:
            out.append(f'<td class="lab">R<sub>{r+1}</sub></td>')
        for c in range(3):
            i = 3 * r + c
            k = []
            if hl_row == r + 1: k.append("hr")
            if hl_col == c + 1: k.append("hc")
            if i in bad: k.append("bad")
            if i in good: k.append("good")
            out.append(f'<td class="{" ".join(k)}">{cells[i]}</td>')
        out.append("</tr>")
    out.append("</table>")
    return "".join(out)

def m(s):
    """Tiny math macro: 'R2^-1' -> <i>R</i><sub>2</sub><sup>−1</sup>, wrapped LTR."""
    letter, rest = s[0], s[1:]
    idx, invp = (rest.split("^") + [""])[:2]
    h = f"<i>{letter}</i><sub>{idx}</sub>"
    if invp:
        h += "<sup>−1</sup>"
    return f'<span class="m">{h}</span>'

# ------------------------------------------------------------- simulate steps
states = [START]
b = START
for mv in SEQUENCE:
    b = apply(b, MOVES[mv])
    states.append(b)
assert states[-1] == SOLVED, states[-1]
# the proposal's own worked example (puzzle 1) as a self-check of the model
assert apply(apply((1, 8, 3, 6, 2, 5, 7, 4, 9), MOVES["C2^-1"]), MOVES["R2^-1"]) == SOLVED
assert apply(SOLVED, MOVES["R2"])[3:6] == (6, 4, 5)
assert tuple(apply(SOLVED, MOVES["C2"])[i] for i in (1, 4, 7)) == (8, 2, 5)

# exhaustive check: distance of START is 4 and the optimal solution is unique
from collections import deque
dist = {SOLVED: 0}; dq = deque([SOLVED])
while dq:
    s = dq.popleft()
    for p in MOVES.values():
        t = apply(s, p)
        if t not in dist:
            dist[t] = dist[s] + 1; dq.append(t)
assert len(dist) == 181440 and max(dist.values()) == 8 and dist[START] == 4
sols = []
def rec(bd, seq):
    if bd == SOLVED and seq: sols.append(list(seq)); return
    if len(seq) == 4: return
    for name, p in MOVES.items():
        seq.append(name); rec(apply(bd, p), seq); seq.pop()
rec(START, [])
assert sols == [SEQUENCE], sols

hl = [(None, None), (2, None), (None, 2), (2, None), (None, 2)]   # tinted line after each move
misplaced = {4, 5, 7}
fig = {}
fig["START"] = board_html(START, bad=misplaced)
fig["START_PLAIN"] = board_html(START)
fig["NUMBERING"] = board_html(SOLVED, labels=True)
fig["CROSS"] = board_html(SOLVED, hl_row=2, hl_col=2, bad=misplaced)
for k, st in enumerate(states):
    r, c = hl[k]
    fig[f"B{k}"] = board_html(st, hl_row=r, hl_col=c)
    fig[f"S{k}"] = board_html(st, hl_row=r, hl_col=c, small=True)
fig["SOLVED"] = board_html(SOLVED, good=set(range(9)))

# distance histogram for the side note
from collections import Counter
hist = sorted(Counter(dist.values()).items())
fa = str.maketrans("0123456789,", "۰۱۲۳۴۵۶۷۸۹٬")
fig["HIST_ROWS"] = "".join(f"<td>{str(n).translate(fa)}</td>" for d, n in hist)
fig["HIST_HEAD"] = "".join(f"<th>{str(d).translate(fa)}</th>" for d, n in hist)

# math macros
for name in list(MOVES):
    fig["m:" + name] = m(name)

tpl = (HERE / "solution.template.html").read_text(encoding="utf-8")
out = tpl
for key, val in fig.items():
    out = out.replace("{{" + key + "}}", val)
assert "{{" not in out, "unreplaced placeholder: " + out[out.index("{{"):out.index("{{") + 40]
(HERE / "solution.html").write_text(out, encoding="utf-8")
print("solution.html written; all assertions passed.")
